/** SVG path covering every cell of `rows` holding `mark`, one rectangle per horizontal run. */
export const pixelPath = (rows: readonly string[], mark: string) =>
  rows
    .flatMap((row, y) =>
      [...row.matchAll(new RegExp(`\\${mark}+`, "g"))].map(
        (run) => `M${run.index} ${y}h${run[0].length}v1h-${run[0].length}z`,
      ),
    )
    .join("");
